/*
 * ตัดสินว่าแถบรูปแบบ (แถวที่สองของแถบเครื่องมือ) ควรโผล่กลุ่มไหนบ้าง
 *
 * ก่อนหน้านี้ตัวควบคุมรูปแบบทั้งหมดถูกวางค้างไว้บนแถบเดียวพร้อมกัน ผู้ใช้จึงต้อง
 * กวาดตาผ่านช่องที่กดไปก็ไม่เกิดอะไร (เช่นความหนาเส้นตอนเลือกกระดาษโน้ต) เพื่อหา
 * ช่องที่ต้องการ ไฟล์นี้คือกฎว่าอะไร "เกี่ยวข้อง" กับสิ่งที่ผู้ใช้กำลังทำอยู่
 *
 * เป็นตรรกะบริสุทธิ์ ไม่แตะ DOM เลย เพื่อให้ตารางเงื่อนไขทั้งตารางทดสอบได้โดย
 * ไม่ต้องสร้างหน้าจอขึ้นมาก่อน ส่วนการซ่อน/แสดงจริงเป็นงานของ toolbar.js
 */

/**
 * ลำดับการแสดงของกลุ่ม เรียงจากสิ่งที่เปลี่ยนบ่อยไปสิ่งที่เปลี่ยนนาน ๆ ครั้ง
 * ตำแหน่งของกลุ่มบนแถบต้องไม่ขยับไปมาตามสิ่งที่เลือก ไม่งั้นผู้ใช้จะกดผิดปุ่ม
 */
export const CONTEXT_GROUPS = ['stroke', 'sticky', 'width', 'font', 'textstyle', 'align'];

/**
 * กลุ่มที่เกี่ยวข้องกับชิ้นงานแต่ละชนิด
 *
 * ชื่อคีย์ตรงกับทั้งชนิดของชิ้นงานและชื่อเครื่องมือที่สร้างมัน (pen, rect, sticky,
 * text, ...) จึงใช้ตารางเดียวตอบได้ทั้ง "เลือกอะไรไว้" และ "ถือเครื่องมืออะไรอยู่"
 * เครื่องมือที่ไม่ได้สร้างชิ้นงาน (hand, select, eraser) ไม่มีในตาราง จึงได้ผลว่าง
 *
 * รูปภาพไม่มีรูปแบบให้ปรับเลย (ปรับขนาดด้วยมือจับบนผืนผ้าใบ) จึงเป็นค่าว่าง
 */
const GROUPS_BY_TYPE = {
    pen: ['stroke', 'width'],
    rect: ['stroke', 'width'],
    ellipse: ['stroke', 'width'],
    line: ['stroke', 'width'],
    arrow: ['stroke', 'width'],
    sticky: ['stroke', 'sticky', 'font', 'textstyle', 'align'],
    text: ['stroke', 'font', 'textstyle', 'align'],
    image: [],
};

/**
 * กลุ่มที่ควรโผล่ในสถานะปัจจุบัน คืนอาร์เรย์ว่างเมื่อไม่ควรมีแถบรูปแบบเลย
 *
 * สิ่งที่เลือกไว้ชนะเครื่องมือที่ถืออยู่ เพราะการเลือกชิ้นงานคือการบอกว่า
 * "ฉันจะแก้ชิ้นนี้" ส่วนเครื่องมือเป็นเพียงสิ่งที่จะใช้ครั้งถัดไป เลือกหลายชิ้น
 * ต่างชนิดได้ผลเป็นการรวมกลุ่มของทุกชนิด (union) ปุ่มที่ใช้กับบางชิ้นไม่ได้จะถูก
 * ตัวจัดการฝั่ง index.js กรองออกเองตอนนำค่าไปใช้
 *
 * ผู้ที่ดูอย่างเดียวไม่มีอะไรให้ปรับ จึงไม่ต้องเสียพื้นที่จอให้แถบที่กดไม่ได้
 * (การบังคับสิทธิ์จริงอยู่ฝั่งเซิร์ฟเวอร์ ที่นี่เป็นเรื่องของหน้าจอเท่านั้น)
 *
 * @param {object} state
 * @param {string} state.tool           ชื่อเครื่องมือที่ถืออยู่
 * @param {string[]} state.selectedTypes ชนิดของชิ้นงานที่เลือกอยู่ (ซ้ำได้)
 * @param {boolean} state.canEdit
 * @returns {string[]} คีย์ของกลุ่ม เรียงตาม CONTEXT_GROUPS เสมอ
 */
export const contextGroupsFor = ({tool, selectedTypes = [], canEdit = true}) => {
    if (! canEdit) {
        return [];
    }

    const sources = selectedTypes.length ? selectedTypes : [tool];
    const wanted = new Set(sources.flatMap((source) => GROUPS_BY_TYPE[source] ?? []));

    return CONTEXT_GROUPS.filter((group) => wanted.has(group));
};
