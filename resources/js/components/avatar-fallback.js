/*
 * รูปโปรไฟล์ที่โหลดไม่ขึ้นต้องกลับไปเป็นตัวย่อชื่อ ไม่ใช่โชว์ไอคอนรูปเสีย
 *
 * Blade เรนเดอร์ <img> เมื่อคอลัมน์ profile_image มีค่า แต่ค่านั้นเป็นเพียง path
 * ในฐานข้อมูล ไม่ได้การันตีว่าไฟล์ยังอยู่จริง (ไฟล์หายตอนย้าย storage, ถูกลบ,
 * หรือถูกกู้คืนบัญชีมาแล้วไฟล์ไม่ได้มาด้วย) เมื่อรูปโหลดไม่ขึ้น เบราว์เซอร์จะแสดง
 * ไอคอนรูปเสียพร้อมข้อความ alt ซึ่งอ่านว่า "รูปโปรไฟล์ของ ..." เต็มการ์ด
 *
 * ใช้ listener ตัวเดียวที่ document ในเฟส capture เพราะ event ชื่อ error ของ
 * <img> ไม่ bubble ขึ้นมาตามปกติ วิธีนี้ครอบคลุมรูปที่ถูกเพิ่มเข้ามาภายหลังด้วย
 * โดยไม่ต้องผูก onerror ไว้ที่ tag ทุกตัว
 *
 * ตัวย่อชื่อถูกเรนเดอร์มาจาก Blade อยู่แล้วในฐานะเนื้อหาสำรองของกล่อง การถอด
 * <img> ออกจึงเผยให้เห็นทันที ไม่ต้องสร้าง DOM ใหม่จาก JavaScript
 */
const FALLBACK_SELECTOR = '[data-avatar-image]';

document.addEventListener(
    'error',
    (event) => {
        const image = event.target;

        if (! (image instanceof HTMLImageElement) || ! image.matches(FALLBACK_SELECTOR)) {
            return;
        }

        // ถอดออกครั้งเดียวพอ ถ้าปล่อยไว้แล้วเปลี่ยน src เบราว์เซอร์จะยิง error ซ้ำไม่จบ
        image.remove();
    },
    true
);
