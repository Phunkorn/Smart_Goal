<?php

namespace App\Support;

use App\Models\User;
use Illuminate\Support\Collection;

/**
 * รายชื่อผู้เข้าร่วมของประชุม/นัดหมายหนึ่งใบ ในรูปร่างที่ปฏิทินและเอกสารใช้ร่วมกัน
 *
 * ทำไมต้องมีชั้นนี้
 * ---------------------------------------------------------------
 * ปฏิทินรวมสอง domain ให้เป็น event รูปร่างเดียว (ดู MeetingAppointmentCalendarQuery)
 * ถ้าปล่อยให้แต่ละ domain map รายชื่อเอง จะได้โค้ดชุดเดียวกันสองที่ แล้วค่อย ๆ
 * ต่างกันทีละนิดจนฝั่งประชุมกับฝั่งนัดหมายแสดงคนคนเดียวกันไม่เหมือนกัน
 * ที่นี่เป็นที่เดียวที่กำหนดว่า "ผู้เข้าร่วมหนึ่งแถว" ประกอบด้วยอะไร
 *
 * ไม่มีสถานะตอบรับในรูปร่างนี้โดยตั้งใจ
 * ---------------------------------------------------------------
 * เอกสารที่พิมพ์ออกมาตอบคำถามว่า "ใครถูกเชิญ" ส่วนใครมาจริงรู้จากลายเซ็นในเอกสาร
 * สถานะตอบรับเป็นข้อมูลของผู้สร้างคนเดียว (...Policy::viewAttendeeResponses)
 * การไม่ดึงมาตั้งแต่ต้นทำให้ไม่มีทางหลุด และไม่ต้องมีการตัดสินสิทธิ์ในเส้นทางนี้เลย
 * ใครต้องการดูคำตอบรายคนยังดูได้ที่หน้ารายละเอียดของรายการนั้นตามเดิม
 *
 * ไม่มีรูปโปรไฟล์ด้วยเหตุผลเดียวกัน — payload นี้ถูกฝังเป็น JSON ทุกครั้งที่เปิด
 * หน้าปฏิทิน การแนบ URL รูปต่อผู้เข้าร่วมทุกคนของทุกรายการในเดือนคือหลายร้อย
 * route() ที่ไม่มีใครใช้ ที่ที่ต้องการ avatar จริงคือหน้ารายละเอียด ไม่ใช่ปฏิทิน
 */
final class CalendarAttendeeRoster
{
    /**
     * @param  Collection<int, User>  $attendees
     * @return array<int, array<string, string>>
     */
    public static function rows(Collection $attendees): array
    {
        return $attendees
            ->map(fn (User $person): array => [
                'name' => $person->name,
                // บทบาทพร้อมแผนกจากแหล่งเดียวของระบบ ไม่ประกอบข้อความเอง
                // ต้องการ role, is_active, is_department_head, department_id ครบ
                // จึงจะไม่แสดงหัวหน้าแผนกเป็น "พนักงาน" — ดู eager load ของผู้เรียก
                'roleLabel' => RoleLabel::withDepartment($person),
            ])
            ->values()
            ->all();
    }
}
